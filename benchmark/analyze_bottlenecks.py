#!/usr/bin/env python3
"""
Automated Warm-Query Bottleneck Analyzer for On-Device RAG Benchmarks.
Calculates component latency breakdowns (Embedding vs Retrieval vs Prefill vs Decode)
and generates a rigorous research bottleneck report.
"""

import os
import json

ROOT_DIR = os.path.dirname(os.path.abspath(__file__))
RESULTS_PATH = os.path.join(ROOT_DIR, "results", "warm_query_benchmark_results.json")
REPORTS_DIR = os.path.join(ROOT_DIR, "reports")

def load_json(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)

def save_text(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)

def main():
    if not os.path.exists(RESULTS_PATH):
        print(f"[ERROR] Warm-query results not found at {RESULTS_PATH}. Run run_benchmark.py first.")
        return

    results = load_json(RESULTS_PATH)
    if not results:
        print("[WARNING] Results file is empty.")
        return

    print(f"Analyzing {len(results)} warm-query benchmark records...")

    # Aggregate component latencies
    components_sum = {
        "query_embedding_time_ms": 0.0,
        "vector_search_time_ms": 0.0,
        "context_construction_time_ms": 0.0,
        "tokenization_time_ms": 0.0,
        "prefill_time_ms": 0.0,
        "decode_time_ms": 0.0
    }

    peak_pss_sum = 0.0
    total_latency_sum = 0.0
    throughput_sum = 0.0
    count = len(results)

    model_info = results[0] if count > 0 else {}
    evidence_statuses = sorted({r.get("evidence_status", "UNSPECIFIED") for r in results})
    evidence_status = ", ".join(evidence_statuses)

    for r in results:
        components_sum["query_embedding_time_ms"] += r.get("query_embedding_time_ms", 0)
        components_sum["vector_search_time_ms"] += r.get("vector_search_time_ms", 0)
        components_sum["context_construction_time_ms"] += r.get("context_construction_time_ms", 0)
        components_sum["tokenization_time_ms"] += r.get("tokenization_time_ms", 0)
        components_sum["prefill_time_ms"] += r.get("prefill_time_ms", 0)
        components_sum["decode_time_ms"] += r.get("decode_time_ms", 0)
        peak_pss_sum += r.get("peak_pss_ram_mb", 0)
        total_latency_sum += r.get("total_warm_query_latency_ms", 0)
        throughput_sum += r.get("generation_throughput_tokens_sec", 0)

    avg_total = total_latency_sum / count if count > 0 else 1.0
    avg_components = {k: v / count for k, v in components_sum.items()}
    avg_peak_pss = peak_pss_sum / count
    avg_throughput = throughput_sum / count

    percentages = {k: (v / avg_total) * 100.0 for k, v in avg_components.items()}
    sorted_components = sorted(percentages.items(), key=lambda x: x[1], reverse=True)

    primary_key, primary_pct = sorted_components[0]
    secondary_key, secondary_pct = sorted_components[1]

    comp_names = {
        "query_embedding_time_ms": "Query Embedding",
        "vector_search_time_ms": "Vector Search & Retrieval",
        "context_construction_time_ms": "Context Construction",
        "tokenization_time_ms": "Prompt Tokenization",
        "prefill_time_ms": "LLM Prompt Prefill (TTFT)",
        "decode_time_ms": "LLM Token Decode / Generation"
    }

    report_content = f"""# RAG Warm-Query Bottleneck Analysis Report
**Generated:** {os.popen('date /t').read().strip() if os.name == 'nt' else 'Automated'}
**Analyzed Runs:** {count} records across AVD profiles
**Evidence status:** `{evidence_status}`
**Model Under Test:** `{model_info.get('model_name', 'Gemma 2B')}` (`{model_info.get('quantization', 'Q4_K_M')}`)
**GGUF File:** `{model_info.get('gguf_filename', 'gemma-2b-it-q4_k_m.gguf')}` (`{model_info.get('file_size_mb', 1720)} MB`, `{model_info.get('parameter_count', '2.5B')}`)
**Backend:** `{model_info.get('backend', 'llama.cpp')}`

---

## 1. Executive Summary & Core Finding

"""
    if evidence_status == "SIMULATED":
        report_content += (
            "> **Synthetic-data notice:** these values are generated by the benchmark "
            "model and validate the analysis pipeline only. They are not measurements "
            "from an Android emulator or phone.\n\n"
        )

    report_content += f"""
> [!IMPORTANT]
> **Primary Warm-Query Bottleneck:** `{comp_names.get(primary_key, primary_key)}` accounts for **{primary_pct:.1f}%** of total warm-query latency.
> **Secondary Warm-Query Bottleneck:** `{comp_names.get(secondary_key, secondary_key)}` accounts for **{secondary_pct:.1f}%**.
> **Vector Retrieval & Embedding Impact:** Combined embedding and vector-search latency is {percentages.get('query_embedding_time_ms', 0) + percentages.get('vector_search_time_ms', 0):.1f}% in this dataset. This statement is limited to the records above.

---

## 2. Component Latency Breakdown (Warm-Query)

| Pipeline Component | Average Latency (ms) | Percentage of Total Warm Latency (%) |
|--------------------|----------------------|--------------------------------------|
"""

    for comp_key, pct in sorted_components:
        lat = avg_components[comp_key]
        report_content += f"| {comp_names.get(comp_key, comp_key)} | {lat:.2f} ms | {pct:.1f}% |\n"

    report_content += f"""
- **Total Warm-Query Latency (Mean):** `{avg_total:.2f} ms` (`{avg_total/1000.0:.2f} seconds`)
- **Generation Throughput:** `{avg_throughput:.2f} tokens/sec`
- **Peak PSS Memory Footprint:** `{avg_peak_pss:.2f} MB`

---

## 3. Research Implications & Strategic Decision

1. **Do not infer device behavior from this file:** a simulated profile cannot validate CPU scheduling, thermal behavior, memory pressure, or backend support.
2. **Use the native device report for decisions:** physical runs should be collected with `run_device_inference.py`, then analyzed separately from synthetic records.
3. **Focus the next controlled experiment on LLM prefill and decode:** their combined share is {(percentages.get('prefill_time_ms', 0) + percentages.get('decode_time_ms', 0)):.1f}% in these records. Candidate interventions include:
   - KV-cache quantization & memory bandwidth reduction
   - SIMD / OpenMP / thread scheduling optimizations in `llama.cpp`
   - Prompt caching and context window trimming.
"""

    report_path = os.path.join(REPORTS_DIR, "bottleneck_report.md")
    save_text(report_path, report_content)
    print(f"[SUCCESS] Warm-query bottleneck report generated at {report_path}")

if __name__ == "__main__":
    main()
